"""What each green screen shows (see fix_screen.py for how they are drawn).

SCREENS[key]:
    model, title, icon, hint        the screen
    kind                            'records' (list + the record on the right), 'table'
                                    (edit in the row), 'settings' (res.config.settings),
                                    'single' (one record, e.g. Booking Desk Settings)
    domain, order, context          which records, in which order
    filters                         the chips: key, label, domain (a list, or a function of env
                                    for "today"), count (show the number on the chip)
    columns, search, badge, image   the list
    modes, board, week, group_by    table / board (by a selection) / week (by a datetime)
    sections                        the record: title, icon, fields (editable), info (read
                                    only), lines (a one2many) + columns, tab, groups, kind
    buttons                         name (the model's method, as on Odoo's form), label, kind,
                                    icon, show (when, a domain), confirm, groups,
                                    odoo (stays in Odoo: invoices, receipts)
    create, create_fields, delete, sequence, notes, locked (no change when this domain matches)

POPUPS[wizard model]: fields (to fill), info (read only), show (when a field shows, a domain
on the pop-up's values), ticks (many2many as tick boxes), widgets, buttons (the wizard's
methods), record (an existing record edited in a pop-up, Save writes it).
"""
