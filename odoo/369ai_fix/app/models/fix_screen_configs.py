def _today(env):
    return fields.Datetime.to_string(datetime.combine(fields.Date.context_today(env['res.users']), time.min))


def _tomorrow(env):
    day = fields.Date.add(fields.Date.context_today(env['res.users']), days=1)
    return fields.Datetime.to_string(datetime.combine(day, time.min))


